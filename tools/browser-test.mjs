import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { build, preview } from 'vite';
import { chromium } from 'playwright';

const base = '/block-city-test/';
const outDir = 'artifacts/subpath-dist';
mkdirSync('artifacts', { recursive: true });
let browser, server;
try {
  await build({ base, build: { outDir }, logLevel: 'warn' });
  server = await preview({ base, build: { outDir }, preview: { host: '127.0.0.1', port: 4178, strictPort: true } });
  const channel = process.env.BROWSER_CHANNEL || 'chrome';
  browser = await chromium.launch({ channel: channel === 'chromium' ? undefined : channel, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const errors = [], requests = [], warnings = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('requestfailed', request => errors.push(`${request.url()} ${request.failure()?.errorText}`));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); requests.push(response.url()); });
  page.on('console', message => { if (message.type() === 'warning') warnings.push(message.text()); if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(`http://127.0.0.1:4178${base}`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('#home-title').textContent(), 'DRIFTCITY');
  assert.equal(await page.evaluate(() => window.blockCity), undefined);
  await page.screenshot({ path: 'artifacts/home.png' });
  await page.locator('#play').hover();
  assert.equal(await page.locator('#play').evaluate(button => getComputedStyle(button).cursor), 'pointer');
  await page.click('#play');
  await page.waitForFunction(() => document.getElementById('home-screen').hidden);
  await page.waitForFunction(() => window.blockCity?.telemetry().grounded === 4);
  await page.waitForTimeout(1500);
  const read = () => page.evaluate(() => window.blockCity.telemetry());
  const initial = await read();
  assert(initial.position.y > 0.45 && initial.position.y < 0.65);
  await page.screenshot({ path: 'artifacts/city.png' });
  await page.keyboard.down('KeyW'); await page.waitForTimeout(2200); await page.keyboard.up('KeyW');
  const acceleration = await read();
  assert(acceleration.signedSpeed > 5); assert(acceleration.position.z > initial.position.z + 5);
  await page.keyboard.down('KeyD'); await page.waitForTimeout(650); await page.keyboard.up('KeyD');
  assert((await read()).steering > 0.05);
  await page.screenshot({ path: 'artifacts/driving.png' });
  await page.keyboard.down('KeyS'); await page.waitForTimeout(2700); await page.keyboard.up('KeyS');
  const reverse = await read(); assert(reverse.signedSpeed < -0.5);
  await page.keyboard.press('KeyR'); await page.waitForTimeout(1800);
  const reset = await read(); assert(Math.abs(reset.position.z - initial.position.z) < 0.02); assert(Math.abs(reset.signedSpeed) < 0.02);
  await page.keyboard.press('KeyC'); assert.equal((await read()).cameraMode, 1);
  await page.keyboard.press('F3'); assert.equal((await read()).debug, true);
  await page.waitForTimeout(500);
  assert.match(await page.locator('#debug').textContent(), /Grounded 4\/4/);
  await page.screenshot({ path: 'artifacts/debug.png' });
  await page.keyboard.press('KeyP'); const paused = await read();
  await page.waitForTimeout(400); assert.equal((await read()).tick, paused.tick);
  await page.click('#resume'); assert.equal((await read()).paused, false);
  await page.keyboard.down('KeyW'); await page.waitForTimeout(300);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  assert.equal((await read()).paused, true); await page.keyboard.up('KeyW');
  await page.keyboard.press('KeyP'); await page.waitForTimeout(500);
  assert.equal((await read()).throttle, 0);
  await page.evaluate(() => { const until = performance.now() + 250; while (performance.now() < until) { /* deliberate stall */ } });
  await page.waitForTimeout(200); assert((await read()).droppedSeconds > 0.1);
  await page.click('#reset'); await page.waitForTimeout(1000);
  await page.setViewportSize({ width: 800, height: 600 });
  await page.keyboard.press('F3'); await page.screenshot({ path: 'artifacts/compact.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  const final = await read();
  assert.equal(errors.length, 0, errors.join('\n'));
  assert(requests.filter(url => url.includes('/assets/')).every(url => url.includes(base)), 'All built assets use the repository subpath');
  const report = { browser: await browser.version(), viewport: '1440x900, 800x600', initial, acceleration, reverse, reset, final, warnings, errors, requests };
  writeFileSync('artifacts/browser-validation.json', JSON.stringify(report, null, 2));
  console.log('PASS Chrome: production subpath, WASM, driving, steering, reverse, reset, cameras, debug, pause, blur, stall, compact viewport.');
  console.log(JSON.stringify({ averageFps: final.averageFps, averageStepMs: final.averageStepMs, drawCalls: final.drawCalls, warnings }));
} finally {
  await browser?.close();
  if (server) await new Promise(resolve => server.httpServer.close(resolve));
}
